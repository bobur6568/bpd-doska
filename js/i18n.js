export const LANGS = ["uz", "en", "ru"];
export const LANG_NAMES = { uz: "UZ", en: "EN", ru: "RU" };
const STORAGE_KEY = "bpd_lang";
const LOCALE = { uz: "uz-UZ", en: "en-US", ru: "ru-RU" };

let currentLang = readStoredLang();

function readStoredLang(){
  try {
    const v = localStorage.getItem(STORAGE_KEY);
    if (v && LANGS.includes(v)) return v;
  } catch (e) { /* localStorage unavailable */ }
  return "uz";
}

export function getLang(){ return currentLang; }

export function setLang(lang){
  if (!LANGS.includes(lang)) return;
  currentLang = lang;
  try { localStorage.setItem(STORAGE_KEY, lang); } catch (e) { /* ignore */ }
  try { document.documentElement.lang = lang; } catch (e) { /* ignore */ }
}

export function localeCode(){ return LOCALE[currentLang] || LOCALE.uz; }

